namespace {

std::atomic<bool> gRunning{false};
std::thread gDaemonThread;

NSString* RouterStatusString() {
  switch (i2p::context.GetStatus()) {
    case i2p::eRouterStatusOK: return @"OK";
    case i2p::eRouterStatusFirewalled: return @"Firewalled";
    case i2p::eRouterStatusUnknown: return @"Testing";
    case i2p::eRouterStatusProxy: return @"Proxy";
    case i2p::eRouterStatusMesh: return @"Mesh";
    case i2p::eRouterStatusStan: return @"Stan";
  }
  return @"—";
}

bool StartDaemon() {
  if (gRunning.load()) return true;

  TrimLog();
  std::string conf = WriteConfig().UTF8String;
  std::string datadir = DataDir().UTF8String;

  // The reseed SU3 signing certificates ship read-only inside this appex.
  // Without them signature verification fails and the router never bootstraps.
  NSString* certs =
      [[[NSBundle mainBundle] resourcePath] stringByAppendingPathComponent:@"certificates"];

  std::vector<std::string> args = {
      "ios2pd",
      "--datadir=" + datadir,
      "--certsdir=" + std::string(certs.UTF8String),
      "--conf=" + conf,
  };
  std::vector<char*> argv;
  argv.reserve(args.size());
  for (auto& arg : args) argv.push_back(&arg[0]);

  // These land in the device console. They are the only trace left if i2pd
  // exits before it opens its own logfile.
  NSLog(@"[ios2pd] datadir=%s certsdir=%s", datadir.c_str(), certs.UTF8String);
  if (!Daemon.init(static_cast<int>(argv.size()), argv.data())) {
    NSLog(@"[ios2pd] Daemon.init failed");
    return false;
  }
  NSLog(@"[ios2pd] Daemon.init ok");
  if (!Daemon.start()) {
    NSLog(@"[ios2pd] Daemon.start failed");
    return false;
  }
  NSLog(@"[ios2pd] Daemon.start ok");

  gRunning.store(true);
  gDaemonThread = std::thread([] { Daemon.run(); });
  return true;
}

void StopDaemon() {
  if (!gRunning.load()) return;
  Daemon.running = false;
  if (gDaemonThread.joinable()) gDaemonThread.join();
  Daemon.stop();
  gRunning.store(false);
}

}  // namespace

