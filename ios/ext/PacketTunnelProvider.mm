// Config
// ---------------------------------------------------------------------------

// i2pd exits the process on an unknown option, so every key here is one that
// exists in this pinned i2pd version.
static NSString* WriteConfig(void) {
  NSMutableString* s = [NSMutableString string];
  [s appendString:@"# generated by ios2pd - rewritten on every connect\n"];
  [s appendString:@"log = file\n"];
  [s appendFormat:@"logfile = %@\n", LogPath()];
  [s appendString:@"loglevel = info\n"];
  // A VPN extension has a much smaller memory budget than an app, so this
  // router is a pure client: it never relays other people's traffic.
  [s appendString:@"notransit = true\n"];
  [s appendString:@"bandwidth = L\n"];
  [s appendString:@"\n[limits]\ntransittunnels = 0\n"];
  [s appendString:@"\n[precomputation]\nelgamal = false\n"];
  [s appendFormat:@"\n[httpproxy]\nenabled = true\naddress = 127.0.0.1\nport = %d\n",
                  kHttpProxyPort];
  [s appendString:@"\n[socksproxy]\nenabled = false\n"];
  [s appendString:@"\n[sam]\nenabled = false\n"];
  [s appendString:@"\n[http]\nenabled = false\n"];
  [s appendString:@"\n[reseed]\nverify = true\n"];

  NSString* path = [DataDir() stringByAppendingPathComponent:@"i2pd.conf"];
  [s writeToFile:path atomically:YES encoding:NSUTF8StringEncoding error:nil];
  return path;
}

