@implementation TunnelEditorViewController

- (instancetype)initWithTunnel:(NSMutableDictionary*)tunnel {
  self = [super initWithStyle:UITableViewStyleInsetGrouped];
  if (self) {
    _tunnel = tunnel;
    _editIndex = -1;
  }
  return self;
}

- (void)viewDidLoad {
  [super viewDidLoad];
  self.navigationItem.title = @"Edit tunnel";
  self.navigationItem.rightBarButtonItem =
