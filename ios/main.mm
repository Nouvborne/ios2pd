- (void)save:(id)sender {
  NSString* name = [_tunnel[@"name"] stringByTrimmingCharactersInSet:
      [NSCharacterSet whitespaceCharacterSet]];
  if (!name.length) {
    [self alert:@"Give the tunnel a name."];
    return;
  }
  int port = [_tunnel[@"port"] intValue];
  if (port < 1 || port > 65535) {
    [self alert:@"Enter a valid local port (1-65535)."];
    return;
  }
  NSString* type = _tunnel[@"type"] ?: @"client";
  if ([type isEqualToString:@"client"] &&
      ![[_tunnel[@"destination"] stringByTrimmingCharactersInSet:
          [NSCharacterSet whitespaceCharacterSet]] length]) {
    [self alert:@"Client tunnels need a destination (e.g. smtp.postman.i2p)."];
    return;
  }
  _tunnel[@"name"] = name;
  NSMutableArray* all = TunnelsList();
  if (_editIndex >= 0 && _editIndex < (NSInteger)all.count) {
    all[_editIndex] = _tunnel;
  } else {
    [all addObject:_tunnel];
  }
  SaveTunnels(all);
  [self.navigationController popViewControllerAnimated:YES];
}

