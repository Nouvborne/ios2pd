- (NSArray*)visibleRows {
  NSString* type = _tunnel[@"type"] ?: @"client";
  NSMutableArray* r = [NSMutableArray arrayWithArray:@[ @"name", @"type", @"port" ]];
  if ([type isEqualToString:@"client"] || [type isEqualToString:@"socks"]) {
    [r addObject:@"address"];
  }
  if ([type isEqualToString:@"client"]) {
    [r addObject:@"destination"];
    [r addObject:@"destinationport"];
  }
  if ([type isEqualToString:@"server"] || [type isEqualToString:@"http"]) {
    [r addObject:@"host"];
    [r addObject:@"inport"];
  }
  [r addObject:@"keys"];
  return r;
}

- (NSString*)labelForKey:(NSString*)key {
  static NSDictionary* labels;
  static dispatch_once_t once;
  dispatch_once(&once, ^{
    labels = @{
      @"name" : @"Name",
      @"type" : @"Type",
      @"port" : @"Local port",
      @"address" : @"Bind address",
      @"destination" : @"Destination (.i2p)",
      @"destinationport" : @"Destination port",
      @"host" : @"Host",
      @"inport" : @"I2P inport",
      @"keys" : @"Keys file",
    };
  });
  return labels[key] ?: key;
}

- (NSInteger)numberOfSectionsInTableView:(UITableView*)tableView {
  return 1;
}

- (NSInteger)tableView:(UITableView*)tableView numberOfRowsInSection:(NSInteger)section {
  return self.visibleRows.count;
}

- (UITableViewCell*)tableView:(UITableView*)tableView cellForRowAtIndexPath:(NSIndexPath*)ip {
  NSString* key = self.visibleRows[ip.row];
  if ([key isEqualToString:@"type"]) {
    UITableViewCell* cell =
        [tableView dequeueReusableCellWithIdentifier:@"type"];
    if (!cell) {
      cell = [[UITableViewCell alloc] initWithStyle:UITableViewCellStyleValue1
                                    reuseIdentifier:@"type"];
    }
    cell.textLabel.text = @"Type";
    cell.detailTextLabel.text = _tunnel[@"type"] ?: @"client";
    cell.accessoryType = UITableViewCellAccessoryDisclosureIndicator;
    return cell;
  }
  NSString* cellId = @"field";
  UITableViewCell* cell = [tableView dequeueReusableCellWithIdentifier:cellId];
  if (!cell) {
    cell = [[UITableViewCell alloc] initWithStyle:UITableViewCellStyleDefault
                                  reuseIdentifier:cellId];
  }
  cell.selectionStyle = UITableViewCellSelectionStyleNone;
  cell.accessoryView = nil;
  for (UIView* sub in cell.contentView.subviews) {
    if ([sub isKindOfClass:[UITextField class]]) [sub removeFromSuperview];
  }
  cell.textLabel.text = [self labelForKey:key];
  UITextField* f = [[UITextField alloc] initWithFrame:CGRectZero];
  f.delegate = self;
  f.returnKeyType = UIReturnKeyDone;
  f.autocorrectionType = UITextAutocorrectionTypeNo;
  f.autocapitalizationType = UITextAutocapitalizationTypeNone;
  NSString* val = _tunnel[key];
  if ([val isKindOfClass:[NSNumber class]]) val = [(NSNumber*)val stringValue];
  f.text = val;
  f.textAlignment = NSTextAlignmentRight;
  BOOL numeric = [key isEqualToString:@"port"] || [key isEqualToString:@"destinationport"] ||
                 [key isEqualToString:@"inport"];
  f.keyboardType = numeric ? UIKeyboardTypeNumberPad : UIKeyboardTypeDefault;
  f.clearButtonMode = UITextFieldViewModeWhileEditing;
  [cell.contentView addSubview:f];
  [f setContentHuggingPriority:UILayoutPriorityRequired
                        forAxis:UILayoutConstraintAxisHorizontal];
  [f setContentCompressionResistancePriority:UILayoutPriorityDefaultLow
                                      forAxis:UILayoutConstraintAxisHorizontal];
  [NSLayoutConstraint activateConstraints:@[
    [f.centerYAnchor constraintEqualToAnchor:cell.contentView.centerYAnchor],
    [f.leadingAnchor constraintEqualToAnchor:cell.textLabel.trailingAnchor constant:12],
    [f.trailingAnchor constraintEqualToAnchor:cell.contentView.trailingAnchor constant:-16],
  ]];
  return cell;
}

- (void)tableView:(UITableView*)tableView didSelectRowAtIndexPath:(NSIndexPath*)ip {
  [tableView deselectRowAtIndexPath:ip animated:YES];
  NSString* key = self.visibleRows[ip.row];
  if (![key isEqualToString:@"type"]) return;
  UIAlertController* sheet =
      [UIAlertController alertControllerWithTitle:@"Tunnel type"
                                          message:nil
                                   preferredStyle:UIAlertControllerStyleActionSheet];
  for (NSString* type in @[ @"client", @"server", @"http", @"socks" ]) {
    [sheet addAction:[UIAlertAction actionWithTitle:type
                                              style:UIAlertActionStyleDefault
                                            handler:^(UIAlertAction* a) {
                                              _tunnel[@"type"] = type;
                                              [self.tableView reloadData];
                                            }]];
  }
  [sheet addAction:[UIAlertAction actionWithTitle:@"Cancel"
                                            style:UIAlertActionStyleCancel
                                          handler:nil]];
  [self presentViewController:sheet animated:YES completion:nil];
}

- (BOOL)textFieldShouldReturn:(UITextField*)field {
  [field resignFirstResponder];
  return YES;
}

- (void)textFieldDidEndEditing:(UITextField*)field {
  UIView* v = field;
  while (v && ![v isKindOfClass:[UITableViewCell class]]) v = v.superview;
  UITableViewCell* cell = (UITableViewCell*)v;
  NSIndexPath* ip = cell ? [self.tableView indexPathForCell:cell] : nil;
  if (!ip) return;
  NSString* key = self.visibleRows[ip.row];
  _tunnel[key] = field.text;
}

- (void)save:(id)sender {
  NSString* name = [_tunnel[@"name"] stringByTrimmingCharactersInSet:
      [NSCharacterSet whitespaceCharacterSet]];
  if (!name.length) {
    [self alert:@"Give the tunnel a name."];
    return;
  }
  int port = [_tunnel[@"port"] intValue];
  if (port < 1 || port > 65535) {
    [self alert:@"Enter a valid local port (1-65535)."];
    return;
  }
  NSString* type = _tunnel[@"type"] ?: @"client";
  if ([type isEqualToString:@"client"] &&
      ![[_tunnel[@"destination"] stringByTrimmingCharactersInSet:
          [NSCharacterSet whitespaceCharacterSet]] length]) {
    [self alert:@"Client tunnels need a destination (e.g. smtp.postman.i2p)."];
    return;
  }
  _tunnel[@"name"] = name;
  NSMutableArray* all = TunnelsList();
  if (_editIndex >= 0 && _editIndex < (NSInteger)all.count) {
    all[_editIndex] = _tunnel;
  } else {
    [all addObject:_tunnel];
  }
  SaveTunnels(all);
  [self.navigationController popViewControllerAnimated:YES];
}

- (void)alert:(NSString*)message {
  UIAlertController* a = [UIAlertController alertControllerWithTitle:@"ios2pd"
                                                              message:message
                                                       preferredStyle:UIAlertControllerStyleAlert];
  [a addAction:[UIAlertAction actionWithTitle:@"OK" style:UIAlertActionStyleDefault handler:nil]];
  [self presentViewController:a animated:YES completion:nil];
}

