//
//  ios2pd — i2pd (I2P daemon) as an iOS app.
//
//  Links the i2pd C++ daemon core (DaemonUnix) into a small UIKit shell.
//  The router runs on a background thread; logs are captured through a
//  custom std::ostream and surfaced in the UI.
//
//  Tabs:
//   - Router   : start/stop the daemon, VPN status, live log.
//   - Tunnels  : client/server tunnels (e.g. mail.i2p / Postman, IRC, ...).
//   - i2pd     : daemon settings (HTTP/SOCKS/SAM proxies, log level,
//                advanced i2pd.conf editor).
//   - Proxy    : backloop.dev integration - install a Wi-Fi proxy profile
//                (.mobileconfig), refresh the loopback SSL certificate, keep
//                i2pd alive in the background, and open the i2pd web console
//                (:7070) through the backloop HTTPS server.
//
//  The daemon is configured from two INI files that this app writes into
//  <Documents>/i2pd:
//    i2pd.conf     - basic settings from the UI + the user's custom block
//                    (appended verbatim from custom.conf).
//    tunnels.conf  - client/server tunnels edited in the Tunnels tab.
//  Both are passed via --conf / --tunconf on start.
//

