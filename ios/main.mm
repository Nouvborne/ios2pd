  NSInteger section = (sw.tag - 100) / 10;
  switch (section) {
    case 0: [UD() setBool:sw.on forKey:kHttpOn]; break;
    case 1: [UD() setBool:sw.on forKey:kSocksOn]; break;
    case 2: [UD() setBool:sw.on forKey:kSamOn]; break;
