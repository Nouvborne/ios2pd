- (void)onToggle:(id)sender {
  if (gStarted.load()) {
    StopDaemon();
    _status.text = @"Stopped";
    _detail.text = @"i2pd is not running";
    [_toggle setTitle:@"Start Router" forState:UIControlStateNormal];
  } else {
    if (StartDaemon()) {
      _status.text = @"Starting…";
      _detail.text = @"Building tunnels";
      [_toggle setTitle:@"Stop Router" forState:UIControlStateNormal];
      InstallVpnProfile();
    } else {
      _detail.text = @"Failed to start - see log";
    }
  }
}

- (void)refresh {
  std::string text = TakeLog();
  if (!text.empty()) {
    NSString* s = [NSString stringWithUTF8String:text.c_str()];
    if (![_log.text isEqualToString:s]) {
      _log.text = s;
      [_log scrollRangeToVisible:NSMakeRange(_log.text.length - 1, 1)];
    }
  }
  if (gStarted.load()) {
    _status.text = @"Running";
    _detail.text = [NSString stringWithFormat:@"%zu tunnels configured",
                                              (size_t)TunnelsList().count];
  }
  _vpn.text = [NSString stringWithFormat:@"VPN: %@", VpnStatusString()];
}

