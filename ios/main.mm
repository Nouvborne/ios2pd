@interface GlassCard : UIVisualEffectView
@end
@implementation GlassCard
- (instancetype)initWithFrame:(CGRect)frame {
  self = [super initWithEffect:[UIBlurEffect effectWithStyle:UIBlurEffectStyleSystemMaterial]];
  if (self) {
    self.layer.cornerRadius = 22;
    self.layer.cornerCurve = kCACornerCurveContinuous;
    self.clipsToBounds = YES;
    self.layer.borderColor = [UIColor colorWithWhite:1.0 alpha:0.18].CGColor;
    self.layer.borderWidth = 1.0 / [UIScreen mainScreen].scale;
  }
  return self;
}
@end

@interface GradientButton : UIButton
@end
@implementation GradientButton {
  CAGradientLayer* _gradient;
}
- (void)layoutSubviews {
  [super layoutSubviews];
  if (!_gradient) {
    _gradient = [CAGradientLayer layer];
    _gradient.colors = @[
      (id)[UIColor systemBlueColor].CGColor,
      (id)[UIColor systemIndigoColor].CGColor,
    ];
    _gradient.startPoint = CGPointMake(0, 0);
    _gradient.endPoint = CGPointMake(1, 1);
    [self.layer insertSublayer:_gradient atIndex:0];
  }
  _gradient.frame = self.bounds;
  _gradient.cornerRadius = self.layer.cornerRadius;
}
@end

static void PinEdges(UIView* sub, UIView* sup, CGFloat top, CGFloat left,
                     CGFloat bottom, CGFloat right) {
  sub.translatesAutoresizingMaskIntoConstraints = NO;
  [NSLayoutConstraint activateConstraints:@[
    [sub.topAnchor constraintEqualToAnchor:sup.topAnchor constant:top],
    [sub.leadingAnchor constraintEqualToAnchor:sup.leadingAnchor constant:left],
    [sub.bottomAnchor constraintEqualToAnchor:sup.bottomAnchor constant:bottom],
    [sub.trailingAnchor constraintEqualToAnchor:sup.trailingAnchor constant:right],
  ]];
}

