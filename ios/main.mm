@interface TunnelsViewController : UITableViewController
@end

@implementation TunnelsViewController

- (instancetype)init {
  self = [super initWithStyle:UITableViewStyleInsetGrouped];
  return self;
}

- (void)viewDidLoad {
  [super viewDidLoad];
  self.navigationItem.title = @"Tunnels";
  self.navigationItem.rightBarButtonItem =
      [[UIBarButtonItem alloc] initWithBarButtonSystemItem:UIBarButtonSystemItemAdd
                                                    target:self
                                                    action:@selector(addTunnel:)];
}

- (void)viewWillAppear:(BOOL)animated {
  [super viewWillAppear:animated];
  [self.tableView reloadData];
}

- (NSArray*)clientTunnels {
  NSMutableArray* a = [NSMutableArray array];
  for (NSDictionary* t in TunnelsList()) {
    NSString* type = t[@"type"] ?: @"client";
    if ([type isEqualToString:@"client"] || [type isEqualToString:@"socks"])
      [a addObject:t];
  }
  return a;
}
- (NSArray*)serverTunnels {
  NSMutableArray* a = [NSMutableArray array];
  for (NSDictionary* t in TunnelsList()) {
    NSString* type = t[@"type"] ?: @"client";
    if ([type isEqualToString:@"server"] || [type isEqualToString:@"http"])
      [a addObject:t];
  }
  return a;
}

- (NSInteger)numberOfSectionsInTableView:(UITableView*)tableView {
  return 2;
}

- (NSInteger)tableView:(UITableView*)tableView numberOfRowsInSection:(NSInteger)section {
  return (section == 0) ? self.clientTunnels.count : self.serverTunnels.count;
}

- (NSString*)tableView:(UITableView*)tableView titleForHeaderInSection:(NSInteger)section {
  return (section == 0) ? @"Client tunnels (outgoing)" : @"Server tunnels (incoming)";
}

- (NSString*)tableView:(UITableView*)tableView titleForFooterInSection:(NSInteger)section {
  if (section == 0) {
    return @"Client tunnels expose a local port that forwards to an I2P "
           @"service - e.g. mail.i2p (Postman), IRC, etc.";
  }
  return @"Server tunnels publish a service running on this device to I2P. "
         @"Changes apply the next time you start the router.";
}

- (UITableViewCell*)tableView:(UITableView*)tableView cellForRowAtIndexPath:(NSIndexPath*)ip {
  UITableViewCell* cell =
      [tableView dequeueReusableCellWithIdentifier:@"tunnel"];
  if (!cell) {
    cell = [[UITableViewCell alloc] initWithStyle:UITableViewCellStyleSubtitle
                                  reuseIdentifier:@"tunnel"];
  }
  NSArray* list = (ip.section == 0) ? self.clientTunnels : self.serverTunnels;
  NSDictionary* t = list[ip.row];
  cell.textLabel.text = t[@"name"];
  cell.textLabel.font = [UIFont systemFontOfSize:16 weight:UIFontWeightSemibold];
  NSString* type = t[@"type"] ?: @"client";
  if ([type isEqualToString:@"client"]) {
    cell.detailTextLabel.text = [NSString stringWithFormat:@"client  %@:%@ -> %@",
                                 t[@"address"] ?: @"127.0.0.1", t[@"port"],
                                 t[@"destination"] ?: @"?"];
  } else if ([type isEqualToString:@"socks"]) {
    cell.detailTextLabel.text = [NSString stringWithFormat:@"socks  %@:%@",
                                 t[@"address"] ?: @"127.0.0.1", t[@"port"]];
  } else if ([type isEqualToString:@"http"]) {
    cell.detailTextLabel.text = [NSString stringWithFormat:@"http  <- %@:%@",
                                 t[@"host"] ?: @"127.0.0.1", t[@"port"]];
  } else {
    cell.detailTextLabel.text = [NSString stringWithFormat:@"server  <- %@:%@",
                                 t[@"host"] ?: @"127.0.0.1", t[@"port"]];
  }
  cell.accessoryType = UITableViewCellAccessoryDisclosureIndicator;
  return cell;
}

- (void)tableView:(UITableView*)tableView didSelectRowAtIndexPath:(NSIndexPath*)ip {
  [tableView deselectRowAtIndexPath:ip animated:YES];
  NSArray* list = (ip.section == 0) ? self.clientTunnels : self.serverTunnels;
  NSDictionary* t = list[ip.row];
  NSArray* all = TunnelsList();
  NSInteger idx = [all indexOfObjectIdenticalTo:t];
  TunnelEditorViewController* ed =
      [[TunnelEditorViewController alloc] initWithTunnel:[t mutableCopy]];
  ed.editIndex = idx;
  [self.navigationController pushViewController:ed animated:YES];
}

- (BOOL)tableView:(UITableView*)tableView canEditRowAtIndexPath:(NSIndexPath*)ip {
  return YES;
}

- (void)tableView:(UITableView*)tableView commitEditingStyle:(UITableViewCellEditingStyle)style
    forRowAtIndexPath:(NSIndexPath*)ip {
  if (style == UITableViewCellEditingStyleDelete) {
    NSArray* list = (ip.section == 0) ? self.clientTunnels : self.serverTunnels;
    NSDictionary* t = list[ip.row];
    NSMutableArray* all = TunnelsList();
    [all removeObjectIdenticalTo:t];
    SaveTunnels(all);
    [tableView deleteRowsAtIndexPaths:@[ ip ]
                     withRowAnimation:UITableViewRowAnimationAutomatic];
  }
}

- (void)addTunnel:(id)sender {
  UIAlertController* sheet =
      [UIAlertController alertControllerWithTitle:@"Add tunnel"
                                          message:nil
                                   preferredStyle:UIAlertControllerStyleActionSheet];
  void (^pushNew)(NSString*, NSString*) = ^(NSString* type, NSString* name) {
    NSMutableDictionary* t = [NSMutableDictionary dictionary];
    t[@"type"] = type;
    t[@"name"] = name;
    t[@"port"] = @"0";
    t[@"address"] = @"127.0.0.1";
    TunnelEditorViewController* ed =
        [[TunnelEditorViewController alloc] initWithTunnel:t];
    ed.editIndex = -1;
    [self.navigationController pushViewController:ed animated:YES];
  };
  [sheet addAction:[UIAlertAction actionWithTitle:@"Client tunnel (to an I2P service)"
                                            style:UIAlertActionStyleDefault
                                          handler:^(UIAlertAction* a) {
                                            pushNew(@"client", @"new-client");
                                          }]];
  [sheet addAction:[UIAlertAction actionWithTitle:@"Server tunnel (host a service)"
                                            style:UIAlertActionStyleDefault
                                          handler:^(UIAlertAction* a) {
                                            pushNew(@"server", @"new-server");
                                          }]];
  [sheet addAction:[UIAlertAction actionWithTitle:@"HTTP tunnel"
                                            style:UIAlertActionStyleDefault
                                          handler:^(UIAlertAction* a) {
                                            pushNew(@"http", @"new-http");
                                          }]];
  [sheet addAction:[UIAlertAction actionWithTitle:@"Postman e-mail preset (mail.i2p)"
                                            style:UIAlertActionStyleDefault
                                          handler:^(UIAlertAction* a) {
                                            [self addPostmanPreset];
                                          }]];
  [sheet addAction:[UIAlertAction actionWithTitle:@"Cancel"
                                            style:UIAlertActionStyleCancel
                                          handler:nil]];
  if (sheet.popoverPresentationController) {
    sheet.popoverPresentationController.barButtonItem = sender;
  }
  [self presentViewController:sheet animated:YES completion:nil];
}

- (void)addPostmanPreset {
  NSMutableArray* all = TunnelsList();
  [all addObject:@{
    @"name" : @"mail-smtp",
    @"type" : @"client",
    @"address" : @"127.0.0.1",
    @"port" : @"515",
    @"destination" : @"smtp.postman.i2p",
    @"keys" : @"mail.dat",
  }];
  [all addObject:@{
    @"name" : @"mail-pop3",
    @"type" : @"client",
    @"address" : @"127.0.0.1",
    @"port" : @"616",
    @"destination" : @"pop.postman.i2p",
    @"keys" : @"mail.dat",
  }];
  SaveTunnels(all);
  [self.tableView reloadData];
}

