//  I2pdCore.mm — i2pd (I2P daemon) core bridge for the ios2pd SwiftUI app.
//
//  Links the i2pd C++ daemon core (DaemonUnix) into the app. The router runs
//  on a background thread; logs are captured through a custom std::ostream and
//  surfaced to the UI.
//
//  The daemon is configured from two INI files this file writes into
//  <Documents>/i2pd:
//    i2pd.conf     - basic settings + the user's custom.conf block (appended).
//    tunnels.conf  - client/server tunnels edited in the Tunnels tab.
//  Both are passed via --conf / --tunconf on start.
//
//  Also owns the backloop.dev integration: refresh the loopback SSL
//  certificate, run the local HTTPS server that serves /install.mobileconfig
//  and relays everything else to the i2pd web console (:7070), plus the
//  i2p-http/i2p-https WKURLSchemeHandler used by the in-app browser.

