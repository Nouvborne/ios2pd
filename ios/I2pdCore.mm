static NSString* ConfDir(void) {
  NSString* docs = [NSSearchPathForDirectoriesInDomains(
      NSDocumentDirectory, NSUserDomainMask, YES) firstObject];
  return [docs stringByAppendingPathComponent:@"i2pd"];
}
static NSString* ConfPath(void) {
  return [ConfDir() stringByAppendingPathComponent:@"i2pd.conf"];
}
static NSString* TunnelsPath(void) {
  return [ConfDir() stringByAppendingPathComponent:@"tunnels.conf"];
}
static NSString* CustomConfPath(void) {
  return [ConfDir() stringByAppendingPathComponent:@"custom.conf"];
}

static BOOL EnsureConfDir(void) {
  NSFileManager* fm = [NSFileManager defaultManager];
  return [fm fileExistsAtPath:ConfDir()] ||
         [fm createDirectoryAtPath:ConfDir() withIntermediateDirectories:YES
                         attributes:nil error:nil];
}

// Persists the tunnels list (array of dicts) to NSUserDefaults.
static NSMutableArray* TunnelsList(void) {
  NSArray* stored = [UD() arrayForKey:kTunnels];
  return stored ? [stored mutableCopy] : [NSMutableArray array];
}
static void SaveTunnels(NSArray* list) {
  [UD() setObject:list forKey:kTunnels];
}

// Writes i2pd.conf from the UI settings + the user's custom.conf block.
static void WriteConfFile(void) {
  EnsureConfDir();
  NSMutableString* s = [NSMutableString string];
  [s appendString:@"# generated by ios2pd - edit via the app\n"];
  [s appendString:@"log = stdout\n"];
  [s appendFormat:@"loglevel = %@\n", SettingString(kLogLevel, @"info")];
  [s appendString:@"\n[httpproxy]\n"];
  [s appendFormat:@"enabled = %@\n", SettingBool(kHttpOn, YES) ? @"true" : @"false"];
  [s appendFormat:@"port = %d\n", SettingInt(kHttpPort, 4444)];
  [s appendString:@"\n[socksproxy]\n"];
  [s appendFormat:@"enabled = %@\n", SettingBool(kSocksOn, YES) ? @"true" : @"false"];
  [s appendFormat:@"port = %d\n", SettingInt(kSocksPort, 4447)];
  [s appendString:@"\n[sam]\n"];
  [s appendFormat:@"enabled = %@\n", SettingBool(kSamOn, YES) ? @"true" : @"false"];
  [s appendFormat:@"port = %d\n", SettingInt(kSamPort, 7656)];
  NSString* custom =
      [NSString stringWithContentsOfFile:CustomConfPath()
                                encoding:NSUTF8StringEncoding error:nil];
  if (custom.length) {
    [s appendString:@"\n# ---- user custom config ----\n"];
    [s appendString:custom];
    if (![custom hasSuffix:@"\n"]) [s appendString:@"\n"];
  }
  [s writeToFile:ConfPath() atomically:YES encoding:NSUTF8StringEncoding
           error:nil];
}

static void WriteTunnelsFile(void) {
  NSArray* tunnels = TunnelsList();
  if (!tunnels.count) return;
  EnsureConfDir();
  NSMutableString* s = [NSMutableString string];
  [s appendString:@"# tunnels configured in the ios2pd app\n"];
  for (NSDictionary* t in tunnels) {
    NSString* name = t[@"name"];
    if (!name.length) continue;
    NSString* type = t[@"type"] ?: @"client";
    [s appendFormat:@"\n[%@]\n", name];
    [s appendFormat:@"type = %@\n", type];
    if ([type isEqualToString:@"client"] || [type isEqualToString:@"socks"]) {
      [s appendFormat:@"address = %@\n", t[@"address"] ?: @"127.0.0.1"];
    }
    [s appendFormat:@"port = %@\n", t[@"port"] ?: @"0"];
    if ([type isEqualToString:@"client"]) {
      [s appendFormat:@"destination = %@\n", t[@"destination"] ?: @""];
      if ([t[@"keys"] length]) [s appendFormat:@"keys = %@\n", t[@"keys"]];
      if ([t[@"destinationport"] length])
        [s appendFormat:@"destinationport = %@\n", t[@"destinationport"]];
    } else if ([type isEqualToString:@"server"] ||
               [type isEqualToString:@"http"]) {
      [s appendFormat:@"host = %@\n", t[@"host"] ?: @"127.0.0.1"];
      if ([t[@"keys"] length]) [s appendFormat:@"keys = %@\n", t[@"keys"]];
      if ([t[@"inport"] length]) [s appendFormat:@"inport = %@\n", t[@"inport"]];
    } else if ([type isEqualToString:@"socks"]) {
      if ([t[@"keys"] length]) [s appendFormat:@"keys = %@\n", t[@"keys"]];
    }
  }
  [s writeToFile:TunnelsPath() atomically:YES encoding:NSUTF8StringEncoding
           error:nil];
}

// Best-effort read of the current Wi-Fi SSID. Returns nil if unavailable (the
// user types it).
static NSString* CurrentSSID(void) {
  NSArray* ifs = (__bridge_transfer NSArray*)CNCopySupportedInterfaces();
  for (NSString* ifname in ifs) {
    NSDictionary* info = (__bridge_transfer NSDictionary*)
        CNCopyCurrentNetworkInfo((__bridge CFStringRef)ifname);
    NSString* ssid = info[(__bridge NSString*)kCNNetworkInfoKeySSID];
    if (ssid.length) return ssid;
  }
  return nil;
}

